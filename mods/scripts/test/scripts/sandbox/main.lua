local function gone(name, value)
  assert(value == nil, name .. " is reachable")
end

gone("io", io)
gone("debug", debug)
gone("package", package)
gone("dofile", dofile)
gone("loadfile", loadfile)
gone("warn", warn)
gone("os.execute", os.execute)
gone("os.getenv", os.getenv)
gone("os.remove", os.remove)
gone("os.exit", os.exit)
gone("string.dump", string.dump)
gone("(\"\").dump", ("").dump)

assert(type(os.time()) == "number" and type(os.clock()) == "number" and type(os.date("%Y")) == "string")
assert(load("return 2 + 3")() == 5)
local chunk, problem = load("\27Lua\x55\0garbage")
assert(chunk == nil and problem:find("binary"), "binary chunks load")
assert(not pcall(setmetatable, {}, { __gc = function() end }), "__gc is accepted")
assert(getmetatable(setmetatable({}, { __index = {} })) ~= nil)
assert(not pcall(require, "../outside"), "require leaves the folder")
assert(not pcall(require, "missing"), "require finds a missing file")
local helper = require("helper")
assert(helper.value == 42 and require("helper") == helper)
assert(not pcall(table.move, {}, 1, 1e15, 1, {}), "table.move takes a huge range")
assert(table.concat(table.move({1, 2, 3}, 1, 3, 1, {}), ",") == "1,2,3")
assert(collectgarbage("count") > 0)
assert(not pcall(collectgarbage, "stop"))

